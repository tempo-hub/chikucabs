export function getCityHub(slug: string) {
  const hub = CITY_HUBS.find((city) => city.slug === slug);
  if (hub) return hub;
  if (CITY_DISPLAY_NAMES[slug]) {
    return { slug, name: CITY_DISPLAY_NAMES[slug] };
  }
  return undefined;
}

